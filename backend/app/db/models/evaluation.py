"""
EvaluationResult ORM model.
"""
import uuid
from datetime import datetime, timezone
from typing import TYPE_CHECKING, Optional
from sqlalchemy import DateTime, Float, ForeignKey, String, func
from sqlalchemy.orm import Mapped, mapped_column, relationship
from sqlalchemy.types import Uuid
from backend.app.db.base import Base, UUIDPrimaryKeyMixin

if TYPE_CHECKING:
    from backend.app.db.models.query_log import QueryLog


class EvaluationResult(Base, UUIDPrimaryKeyMixin):
    """
    EvaluationResult entity storing quantitative quality metrics (Faithfulness,
    Answer Relevance, Context Precision) generated by benchmark evaluators or LLM-judges.
    """
    __tablename__ = "evaluation_results"

    query_log_id: Mapped[uuid.UUID] = mapped_column(
        Uuid,
        ForeignKey("query_logs.id", ondelete="CASCADE"),
        index=True,
        nullable=False,
    )
    faithfulness_score: Mapped[Optional[float]] = mapped_column(
        Float,
        nullable=True,
        comment="0.0 to 1.0 score measuring factual consistency against evidence",
    )
    answer_relevance_score: Mapped[Optional[float]] = mapped_column(
        Float,
        nullable=True,
        comment="0.0 to 1.0 score measuring alignment with user question",
    )
    context_precision_score: Mapped[Optional[float]] = mapped_column(
        Float,
        nullable=True,
        comment="0.0 to 1.0 score measuring proportion of relevant chunks in context",
    )
    evaluation_model: Mapped[Optional[str]] = mapped_column(
        String(100),
        nullable=True,
        comment="Name of judge model (e.g. gpt-4o, ragas, claude-3-5)",
    )
    evaluated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
        server_default=func.now(),
        nullable=False,
    )

    # Relationships
    query_log: Mapped["QueryLog"] = relationship(
        "QueryLog",
        back_populates="evaluations",
        lazy="joined",
    )

    def __repr__(self) -> str:
        return f"<EvaluationResult(id={self.id}, query_log_id={self.query_log_id}, faithfulness={self.faithfulness_score})>"
